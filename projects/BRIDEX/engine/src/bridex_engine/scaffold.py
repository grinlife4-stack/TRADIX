"""Generate safe, draft-only Bridge project skeletons."""

from __future__ import annotations

import json
import os
import re
import shutil
import tempfile
import uuid
from pathlib import Path
from typing import Any

from .manifest import validate_manifest_data


def _slug(value: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError("bridge_name_required")
    result = re.sub(r"[^a-z0-9]+", "-", value.strip().lower()).strip("-")
    if not result or not result[0].isalpha():
        raise ValueError("bridge_name_must_produce_package_slug")
    return result[:63].rstrip("-")


def create_bridge_project(
    destination: str | Path,
    *,
    name: str,
    owner_id: str,
    owner_assignment_ref: str,
    operator_id: str,
    operator_assignment_ref: str,
    version: str = "0.1.0",
    bridge_id: str | None = None,
) -> Path:
    """Create an independent Bridge skeleton with no trusted peers or enabled capabilities.

    The generated project contains no network client, credentials, secrets, or
    active OBIS transport. Its OBIS binding is explicitly unconfigured.
    """
    module_name = _slug(name).replace("-", "_")
    raw_target = Path(destination).expanduser()
    if raw_target.name in {"", ".", ".."} or raw_target.is_symlink():
        raise ValueError("bridge_destination_invalid")
    raw_target.parent.mkdir(parents=True, exist_ok=True)
    parent = raw_target.parent.resolve(strict=True)
    target = parent / raw_target.name
    if target.exists() or target.is_symlink():
        raise FileExistsError("bridge_destination_must_not_exist")

    manifest: dict[str, Any] = {
        "manifest_version": "0.1",
        "bridge_id": bridge_id or f"urn:uuid:{uuid.uuid4()}",
        "version": version,
        "name": name.strip(),
        "owner": {
            "entity_id": owner_id,
            "assignment_ref": owner_assignment_ref,
        },
        "operator": {
            "entity_id": operator_id,
            "assignment_ref": operator_assignment_ref,
        },
        "obis": {
            "version": "0.1",
            "transport_binding": "unconfigured",
            "security_profile": "unconfigured",
        },
        "runtime": {
            "kind": "python",
            "entrypoint": f"src/{module_name}/__init__.py",
            "independent": True,
        },
        "peers": [],
        "capabilities": [],
        "lifecycle": "draft",
        "package_files": [
            "README.md",
            "config/bridge.example.json",
            "pyproject.toml",
            f"src/{module_name}/__init__.py",
            "tests/test_bridge_contract.py",
        ],
        "dependencies": [],
    }
    validate_manifest_data(manifest)

    staging = Path(tempfile.mkdtemp(prefix=".bridex-init-", dir=parent))
    try:
        (staging / "config").mkdir()
        (staging / "src" / module_name).mkdir(parents=True)
        (staging / "tests").mkdir()
        (staging / "bridge.json").write_text(
            json.dumps(manifest, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        (staging / "README.md").write_text(
            f"# {name.strip()}\n\n"
            f"Bridge ID: `{manifest['bridge_id']}`\n\n"
            "This is an independently owned, draft-only Bridge project generated by BRIDEX.\n\n"
            "- Owner and operator are recorded separately with assignment evidence.\n"
            "- No peer is trusted.\n"
            "- No capability is enabled.\n"
            "- OBIS transport and security profiles are unconfigured.\n"
            "- No credentials, secrets, network listeners, or outbound network clients are included.\n"
            "- This project has no TRADIX or BRIDEX runtime dependency.\n\n"
            "Before implementation, the owner must define the capability contracts, peer trust, "
            "security profile, data boundaries, operational controls, and acceptance tests.\n",
            encoding="utf-8",
        )
        (staging / "pyproject.toml").write_text(
            "[build-system]\nrequires = [\"setuptools>=68\"]\n"
            "build-backend = \"setuptools.build_meta\"\n\n"
            f"[project]\nname = \"bridge-{module_name}\"\n"
            f"version = \"{version}\"\n"
            "requires-python = \">=3.11\"\n"
            "dependencies = []\n\n"
            "[tool.setuptools.packages.find]\nwhere = [\"src\"]\n",
            encoding="utf-8",
        )
        (staging / "config" / "bridge.example.json").write_text(
            json.dumps(
                {"peers": [], "enabled_capabilities": [], "transport_enabled": False},
                indent=2,
                sort_keys=True,
            ) + "\n",
            encoding="utf-8",
        )
        (staging / "src" / module_name / "__init__.py").write_text(
            '"""Bridge-specific implementation belongs to this independent project."""\n',
            encoding="utf-8",
        )
        (staging / "tests" / "test_bridge_contract.py").write_text(
            "import json\nfrom pathlib import Path\n\n"
            "def test_generated_bridge_is_draft_and_disabled():\n"
            "    root = Path(__file__).parents[1]\n"
            "    manifest = json.loads((root / \"bridge.json\").read_text(encoding=\"utf-8\"))\n"
            "    assert manifest[\"lifecycle\"] == \"draft\"\n"
            "    assert manifest[\"peers\"] == []\n"
            "    assert manifest[\"capabilities\"] == []\n"
            "    assert manifest[\"obis\"][\"transport_binding\"] == \"unconfigured\"\n",
            encoding="utf-8",
        )
        os.rename(staging, target)
    except Exception:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    return target
